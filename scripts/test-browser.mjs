import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { mkdir, writeFile } from 'node:fs/promises';
const base = process.env.BASE_URL || 'http://localhost:8080';
await mkdir('target/browser', {recursive:true});
const browser = await chromium.launch({headless:true});
let page;
try {
  const context = await browser.newContext({viewport:{width:1440,height:1080}});
  page = await context.newPage();
  const errors=[]; page.on('pageerror', error=>errors.push(error.message));
  await page.goto(base); await page.locator('#landing').waitFor({state:'visible'});
  await page.screenshot({path:'target/browser/01-home.png',fullPage:true});
  await page.click('#start-button'); await page.fill('#character-name','Nova');
  await page.click('#character-form button[type=submit]');
  await page.locator('#dashboard').waitFor({state:'visible'});
  assert.equal(await page.locator('#profile-name').textContent(),'Nova');
  await page.screenshot({path:'target/browser/02-contract.png',fullPage:true});
  await page.locator('.choice', {hasText:'Pagar pela passagem'}).click();
  await page.click('#confirm-choice');
  await page.waitForFunction(()=>document.getElementById('mission-title').textContent==='O chip que sangra');
  assert.match(await page.locator('#money-value').textContent(),/700/);
  await page.locator('.choice',{hasText:'Proteger Lia'}).click(); await page.click('#confirm-choice');
  await page.waitForFunction(()=>document.getElementById('mission-title').textContent==='Carne de reposição');
  assert.equal(await page.locator('.choice',{hasText:'Usar o contato de Lia'}).isEnabled(),true);
  assert.match(await page.locator('#mission-memory').textContent(),/Lia/);
  await page.locator('.choice',{hasText:'Usar o contato de Lia'}).click(); await page.click('#confirm-choice');
  await page.waitForFunction(()=>document.getElementById('mission-title').textContent==='Um andar acima');
  await page.click('[data-tab=clinic]');
  const deck=page.locator('.shop-card',{hasText:'Cyberdeck Íris'});
  await deck.locator('button').click(); await page.click('#confirm-choice');
  await page.waitForFunction(()=>document.getElementById('slots-label').textContent==='1 / 3 SLOTS OCUPADOS');
  await page.screenshot({path:'target/browser/03-clinic.png',fullPage:true});
  await page.click('[data-tab=mission]');
  assert.equal(await page.locator('.choice',{hasText:'Entrar pelo sistema'}).isEnabled(),true);
  await page.reload(); await page.locator('#dashboard').waitFor({state:'visible'});
  assert.equal(await page.locator('#profile-name').textContent(),'Nova');
  assert.equal(await page.locator('#mission-title').textContent(),'Um andar acima');
  await page.click('[data-tab=district]');
  const priorDay=await page.locator('#day-label').textContent();
  await page.click('[data-action=rest]');
  await page.waitForFunction(previous=>document.getElementById('day-label').textContent!==previous,priorDay);
  await page.click('[data-tab=dossier]');
  assert.match(await page.locator('#journal-list').textContent(),/Implante instalado/);
  const download=page.waitForEvent('download'); await page.click('#export-button');
  assert.equal((await download).suggestedFilename(),'chromeprotocol-dossie.json');
  await page.setViewportSize({width:390,height:844});
  await page.click('[data-tab=mission]');
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth),false,'Mobile has no horizontal overflow');
  await page.screenshot({path:'target/browser/04-mobile.png',fullPage:true});
  await page.click('.new-career-button:visible').catch(async()=>{
    await page.click('[data-tab=dossier]'); await page.click('.new-career-button:visible');
  });
  await page.fill('#character-name','<b>Nova</b>');
  await page.click('#character-form button[type=submit]');
  await page.locator('#dashboard').waitFor({state:'visible'});
  assert.equal(await page.locator('#profile-name').textContent(),'<b>Nova</b>');
  assert.equal(await page.locator('#profile-name b').count(),0,'User names are rendered as text');
  assert.equal(await page.locator('#mission-title').textContent(),'Um nome no asfalto');
  const isolated=await browser.newContext(); const other=await isolated.newPage();
  await other.goto(base); await other.locator('#landing').waitFor({state:'visible'}); await isolated.close();
  assert.deepEqual(errors,[],'No uncaught browser errors');
  await writeFile('target/browser/result.txt','Browser checks passed: creation, choices, narrative unlocks, implants, persistence, rest, export, mobile, restart, escaping and isolation.\n');
  console.log('Browser checks passed.');
} catch(error) {
  if(page) await page.screenshot({path:'target/browser/failure.png',fullPage:true}).catch(()=>{});
  throw error;
} finally { await browser.close(); }
